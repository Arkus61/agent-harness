ROOT=Path(__file__).resolve().parent
SOURCE_NAMES=['suite.py','cases.py','advanced.py','test_suite.py','structure-check/Cargo.toml','structure-check/Cargo.lock','structure-check/src/main.rs']
CARGO='[package]\nname="harness_benchmark_fixture"\nversion="0.1.0"\nedition="2021"\n[dependencies]\n'
LOCK='# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "harness_benchmark_fixture"\nversion = "0.1.0"\n'


def module(name):
    spec=importlib.util.spec_from_file_location('benchmark_'+name,ROOT/(name+'.py'))
    result=importlib.util.module_from_spec(spec)
    # Advanced definitions import the exact same frozen cases module.
    old=sys.modules.get('cases');sys.modules['cases']=result if name=='cases' else module('cases')
    try:spec.loader.exec_module(result)
    finally:
        if old is None:sys.modules.pop('cases',None)
        else:sys.modules['cases']=old
    return result


def cases():
    return module('cases').definitions()+module('advanced').definitions()


def task_spec(case):
    owned=['tests/**'] if case['family']=='Q06' else ['src/**','tests/**']
    protected=['Cargo.toml','Cargo.lock','acceptance/**']+case.get('protected',[])
    prompt=case['id']+': '+case['title']+'. '+ ' '.join(case['requirements'])+' Do not claim tool verification; trusted protected checks run cargo test. Oracles are not inside your repository.'
    if case.get('nodes'):
        nodes=[{'id':name,'prompt':prompt+' Implement your owned component and add tests in its module.','requirements':list(range(len(case['requirements']))),'depends_on':[],'owned_paths':paths}for name,paths in case['nodes']]
    else:
        nodes=[{'id':'implement','prompt':'Read source and implement all requirements; add meaningful regression assertions.','requirements':list(range(len(case['requirements']))),'depends_on':[],'owned_paths':owned}]
    return {'schema_version':1,'prompt':prompt,'requirements':case['requirements'],
            'grants':{'read':['src/**','tests/**','docs/**','catalog/**','Cargo.toml','Cargo.lock'],'write':owned,'commands':[]},
            'checks':[{'program':'cargo','args':['test','--locked','--offline'],'timeout_secs':120}],
            'protected_paths':protected,'provider':{'kind':'chatgpt','codex_program':'codex','model':'gpt-6.1-sol','allow_remote':True},
            'nodes':nodes,'profile':'isolated','decision_mode':'enforced',
            'budget':{'max_tokens':500000,'max_output_tokens':4096,'deadline_secs':1200},
            'concurrency':2,'max_steps':12,'max_repairs':2,'context_bytes':48000,'secrets':[],'skills':case.get('skills',[])}


def configurations():
    return {'H':{'status':'available','definition':'Frozen current TaskSpec, isolated, enforced, curated-memory/skills enabled, static node DAG, four reviewers.','fair_comparison_executed':False},
            'B0':{'status':'unavailable','reason':'No Engine flags for single-agent candidate-only ablation with decisions/memory/skills/reviews disabled. Reusing H would not be a baseline.','fair_comparison_executed':False},
            'B1':{'status':'unavailable','reason':'No Engine flags for baseline-multiagent ablation disabling H extras under equal vector budget.','fair_comparison_executed':False}}


def file_hash(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def values_hash(value):return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode()).hexdigest()


def source_hash():
    digest=hashlib.sha256()
    for relative in SOURCE_NAMES:
        digest.update(relative.encode()+b'\0');digest.update((ROOT/relative).read_bytes()+b'\0')
    return digest.hexdigest()


def directory_hash(path):
    digest=hashlib.sha256()
    for entry in sorted(Path(path).rglob('*')):
        if entry.is_file() and '.git' not in entry.relative_to(path).parts and 'target' not in entry.relative_to(path).parts:
            digest.update(entry.relative_to(path).as_posix().encode()+b'\0');digest.update(entry.read_bytes()+b'\0')
    return digest.hexdigest()


def require_frozen(path,expected):
    if file_hash(path)!=expected:raise ValueError('Frozen file changed: '+str(path))


def safe_archive_name(name):
    if not name or name.startswith('/') or '\\' in name or '\0' in name:return False
    parts=Path(name).parts
    return '..' not in parts and not any(p in {'.git','.cargo','.harness'} for p in parts) and name!='build.rs'


def verify_receipt(receipt,expected):
    return receipt.get('status')=='PASS' and all(receipt.get(k)==v for k,v in expected.items())


def mutation_killed(receipt):
    return receipt.get('exit_code')==101 and receipt.get('assertion_failure') is True and receipt.get('compiled') is True


def materialize(case,target,control=False):
    target=Path(target);target.mkdir(parents=True,exist_ok=True)
    (target/'Cargo.toml').write_text(CARGO);(target/'Cargo.lock').write_text(LOCK)
    files={**case['baseline'],**(case['control'] if control else {})}
    for name,content in files.items():
        if not safe_archive_name(name):raise ValueError('Unsafe frozen fixture path')
        path=target/name;path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    large=case.get('large_context')
    if large:
        folder=target/'catalog';folder.mkdir()
        for index in range(large['count']):(folder/f'route-{index:05}.txt').write_text(f'Archived unrelated route {index:05}. Not the current shipping surcharge rule.\n')
        (target/large['relevant_file']).write_text(large['content'])


def git(repo,*args):
    return subprocess.check_output(['git','-C',str(repo),*args],text=True).strip()


def initialize(repo,label):
    env=os.environ.copy();env.update({'GIT_AUTHOR_NAME':'Harness Benchmark','GIT_AUTHOR_EMAIL':'benchmark@localhost','GIT_COMMITTER_NAME':'Harness Benchmark','GIT_COMMITTER_EMAIL':'benchmark@localhost','GIT_AUTHOR_DATE':'2026-10-02T00:00:00+00:00','GIT_COMMITTER_DATE':'2026-10-02T00:00:00+00:00'})
    for cmd in [['git','init','-q','-b','main'],['git','add','.'],['git','-c','commit.gpgsign=false','commit','-qm',label]]:subprocess.run(cmd,cwd=repo,env=env,check=True)
    return git(repo,'rev-parse','HEAD')


def save(path,value):
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True);path.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n')


def toolchain():
    rustup=Path(os.environ.get('RUSTUP_HOME','/workspace/.rustup'))
    matches=sorted((rustup/'toolchains').glob('1.99.0-*'))
    if not matches:raise RuntimeError('Pinned Rust 1.99.0 toolchain unavailable')
    return matches[0].resolve()


def isolated_command(command,work,timeout=120,extra_env=None,readonly_roots=()):
    if sys.platform!='linux':raise RuntimeError('Linux isolated external oracle unavailable on this platform; no native downgrade')
    bwrap=Path('/usr/bin/bwrap')
    if not bwrap.is_file() or bwrap.stat().st_uid!=0 or bwrap.stat().st_mode&0o022:raise RuntimeError('Trusted bubblewrap unavailable')
    args=[str(bwrap),'--unshare-all','--unshare-user','--disable-userns','--die-with-parent','--new-session','--cap-drop','ALL','--clearenv','--proc','/proc','--dev','/dev','--tmpfs','/tmp','--dir','/usr']
    for path in ['/usr/bin','/usr/lib','/usr/lib64','/usr/libexec','/usr/include']:
        if Path(path).is_dir():
            metadata=Path(path).stat()
            if metadata.st_uid!=0 or metadata.st_mode&0o022:raise RuntimeError('Untrusted system toolchain mount')
            args+=['--ro-bind',path,path]
    args+=['--symlink','usr/bin','/bin','--symlink','usr/lib','/lib']
    if Path('/usr/lib64').is_dir():args+=['--symlink','usr/lib64','/lib64']
    args+=['--ro-bind',str(toolchain()),'/toolchain','--bind',str(Path(work).resolve()),'/sandbox','--chdir','/sandbox',
           '--setenv','PATH','/toolchain/bin:/usr/bin','--setenv','HOME','/tmp','--setenv','CARGO_HOME','/tmp/cargo',
           '--setenv','CARGO_NET_OFFLINE','true','--setenv','CARGO_TERM_COLOR','never','--setenv','RUSTFLAGS','-C linker=/usr/bin/gcc']
    for root in readonly_roots:
        root=Path(root).resolve();relative=root.relative_to(Path(work).resolve());target=root/'target';target.mkdir(exist_ok=True)
        args+=['--ro-bind',str(root),'/sandbox/'+str(relative),'--bind',str(target),'/sandbox/'+str(relative)+'/target']
    for key,value in (extra_env or {}).items():args+=['--setenv',key,str(value)]
    args+=command
    started=time.monotonic()
    process=subprocess.Popen(args,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True,start_new_session=True)
    try:
        stdout,stderr=process.communicate(timeout=timeout)
        timed_out=False
    except subprocess.TimeoutExpired:
        os.killpg(process.pid,signal.SIGKILL);stdout,stderr=process.communicate();timed_out=True
    combined=stdout+'\n'+stderr
    return {'exit_code':process.returncode,'timed_out':timed_out,'compiled':('Finished `test` profile' in combined and 'error: could not compile' not in combined and 'error[E' not in combined and not timed_out),
            'assertion_failure':'test result: FAILED' in combined,'elapsed_seconds':round(time.monotonic()-started,3),
            'tests':re.findall(r'^test (\S+) \.\.\. (ok|FAILED)$',stdout,re.M),'stdout':stdout[-20000:],'stderr':stderr[-20000:],
            'profile':'linux-bubblewrap','filesystem_isolated':True,'network_isolated':True,'host_credentials_mounted':False}


def structure_check(case,candidate):
    if not case.get('structure'):return {'status':'NOT_APPLICABLE'}
    checker=ROOT/'structure-check'
    executable=checker/'target/release/harness-benchmark-structure'
    env=os.environ.copy();env.update({'CARGO_NET_OFFLINE':'true'})
    build=subprocess.run(['cargo','build','--release','--locked','--offline','--manifest-path',str(checker/'Cargo.toml')],capture_output=True,text=True,env=env,timeout=180)
    if build.returncode:raise RuntimeError('Independent AST oracle build failed: '+build.stderr[-1000:])
    process=subprocess.run([str(executable),case['structure']['kind'],str(candidate/'src/lib.rs')],capture_output=True,text=True,timeout=10)
    result=json.loads(process.stdout)
    if process.returncode!={'PASS':0,'FAIL':1,'ERROR':2}.get(result.get('status')):raise RuntimeError('Invalid AST oracle receipt')
    return {**result,'executable_sha256':file_hash(executable),'checker_sources_sha256':values_hash({p:file_hash(checker/p) for p in ['Cargo.toml','Cargo.lock','src/main.rs']})}


def evaluate(case,repo,candidate_ref,scenario_evidence=None):
    frozen_sources=source_hash()
    sha=git(repo,'rev-parse','--verify',candidate_ref+'^{commit}');tree=git(repo,'rev-parse',sha+'^{tree}')
    outcome={'schema_version':1,'task_id':case['id'],'candidate_sha':sha,'candidate_tree':tree,'status':'FAIL',
             'task_sha256':values_hash(task_spec(case)),'oracle_sha256':values_hash({'oracle':case['oracle'],'mutants':case.get('mutants'),'structure':case.get('structure'),'setup':case.get('setup'),'evidence':case.get('evidence')}),
             'suite_sources_sha256':frozen_sources,'case_sha256':values_hash(case),'external_oracle_profile':'linux-bubblewrap','agent_oracle_access':'not_mounted_in_agent_repo',
             'external_test_code_secret_during_execution':False,'complete_family_scenario_proved':not bool(case.get('setup') or case.get('evidence'))}
    with tempfile.TemporaryDirectory(prefix='harness-benchmark-oracle-') as directory:
        work=Path(directory);candidate=work/'candidate';candidate.mkdir()
        archive=subprocess.check_output(['git','-C',str(repo),'archive',sha])
        with tarfile.open(fileobj=io.BytesIO(archive))as bundle:
            entries=bundle.getmembers()
            if any(not safe_archive_name(e.name)or not(e.isdir()or e.isfile())for e in entries):
                outcome['reason']='Candidate archive contains unsafe path, links or build configuration';return outcome
            bundle.extractall(candidate,filter='data')
        expected={'Cargo.toml':CARGO,'Cargo.lock':LOCK}
        for pattern in case.get('protected',[]):
            if pattern.endswith('/**'):
                prefix=pattern[:-3]
                if case.get('large_context') and prefix=='catalog':
                    expected[case['large_context']['relevant_file']]=case['large_context']['content']
                    # Every distractor is frozen too, not only the relevant rule.
                    for index in range(case['large_context']['count']):
                        name=f'catalog/route-{index:05}.txt';expected.setdefault(name,f'Archived unrelated route {index:05}. Not the current shipping surcharge rule.\n')
                expected.update({p:v for p,v in case['baseline'].items()if p.startswith(prefix+'/')})
            else:expected[pattern]=case['baseline'][pattern]
        protected={p:(candidate/p).is_file()and(candidate/p).read_text()==value for p,value in expected.items()}
        outcome['protected_contract']={'all_unchanged':all(protected.values()),'checked_files':len(protected),'changed_files':[p for p,ok in protected.items()if not ok]}
        if not all(protected.values()):outcome['reason']='Protected source/build contract changed';return outcome
        # Check exact candidate sources before the external oracle exists.
        check_script='set -e; cd /sandbox/candidate; cargo test --locked --offline; cargo build --locked --offline --bins'
        outcome['candidate_checks']=isolated_command(['/usr/bin/sh','-c',check_script],work,readonly_roots=[candidate])
        oracle=work/'acceptance';(oracle/'tests').mkdir(parents=True)
        (oracle/'Cargo.toml').write_text('[package]\nname="benchmark_acceptance"\nversion="0.1.0"\nedition="2021"\n[dependencies]\nfixture={package="harness_benchmark_fixture",path="../candidate"}\n')
        (oracle/'tests/contract.rs').write_text(case['oracle'])
        (oracle/'Cargo.lock').write_text(LOCK+'\n[[package]]\nname = "benchmark_acceptance"\nversion = "0.1.0"\ndependencies = ["harness_benchmark_fixture"]\n')
        # Paths are sandbox-relative; frozen oracle never executes candidate on host.
        script='set -e; cd /sandbox/acceptance; cargo test --locked --offline --test contract'
        # No candidate-derived command string is interpolated. Shell script is fixed trusted code.
        outcome['behavior']=isolated_command(['/usr/bin/sh','-c',script],work,extra_env={'FIXTURE_BINARY':'/sandbox/candidate/target/debug/harness_benchmark_fixture'},readonly_roots=[candidate,oracle])
        outcome['structure']=structure_check(case,candidate)
        mutation_results={}
        for name,files in case.get('mutants',{}).items():
            originals={p:(candidate/p).read_bytes()for p in files}
            for p,v in files.items():(candidate/p).write_text(v)
            receipt=isolated_command(['/toolchain/bin/cargo','test','--locked','--offline','--manifest-path','/sandbox/candidate/Cargo.toml','--tests'],work,readonly_roots=[candidate,oracle])
            receipt['killed']=mutation_killed(receipt);mutation_results[name]=receipt
            for p,v in originals.items():(candidate/p).write_bytes(v)
        if mutation_results:outcome['mutants']=mutation_results
        behavior=outcome['behavior'];passed=outcome['candidate_checks']['exit_code']==0 and behavior['exit_code']==0 and bool(behavior['tests']) and not behavior['timed_out']
        passed=passed and outcome['structure']['status']in ['PASS','NOT_APPLICABLE'] and all(m['killed']for m in mutation_results.values())
        outcome['status']='PASS'if passed else'FAIL'
    if source_hash()!=frozen_sources:raise RuntimeError('Benchmark controller/oracle definitions changed during grading')
    outcome['scenario_status']='PASS'if passed and outcome['complete_family_scenario_proved']else'NOT_PROVED'
    if scenario_evidence is not None:outcome['supplied_scenario_evidence']=scenario_evidence
    return outcome


def prepare(output,selected=None):
    output=Path(output).resolve()
    if output.exists():raise ValueError('Freeze output must be fresh; historical evidence is never overwritten')
    output.mkdir(parents=True)
    manifest={'schema_version':1,'suite':'thirty_independent_rust_tasks','suite_sources_sha256':source_hash(),'configurations':configurations(),'model':'gpt-6.1-sol','fresh_repeats':3,
              'task_count':30,'split_counts':{'dev':20,'holdout':10},'holdout_hidden_from_developers':False,'oracle_profile':'linux-bubblewrap','live_execution_status':'not_executed','tasks':[]}
    chosen=[c for c in cases()if selected is None or c['id']in selected]
    for case in chosen:
        seed=output/'seeds'/case['id'];materialize(case,seed);sha=initialize(seed,'Frozen benchmark baseline '+case['id'])
        baseline=evaluate(case,seed,sha);save(output/'receipts'/f"{case['id']}-baseline.json",baseline)
        with tempfile.TemporaryDirectory(prefix='harness-benchmark-control-')as directory:
            control=Path(directory)/'control';materialize(case,control,True);control_sha=initialize(control,'Known valid control '+case['id']);valid=evaluate(case,control,control_sha)
        save(output/'receipts'/f"{case['id']}-control.json",valid)
        task_path=output/'tasks'/f"{case['id']}.json";save(task_path,task_spec(case))
        entry={'id':case['id'],'split':case['split'],'title':case['title'],'seed':str(seed),'task_file':str(task_path),'task_file_sha256':file_hash(task_path),'task_sha256':baseline['task_sha256'],'baseline_sha':sha,'baseline_tree':git(seed,'rev-parse','HEAD^{tree}'),'fixture_sha256':directory_hash(seed),'oracle_sha256':baseline['oracle_sha256'],'case_sha256':values_hash(case),'baseline_status':baseline['status'],'control_status':valid['status'],'red_green':'PASS'if baseline['status']=='FAIL'and valid['status']=='PASS'else'FAIL','setup':case.get('setup'),'evidence':case.get('evidence'),'complete_family_scenario_proved':False}
        manifest['tasks'].append(entry);save(output/'manifest.json',manifest)
        print(json.dumps({'id':case['id'],'baseline':baseline['status'],'control':valid['status'],'red_green':entry['red_green']}),flush=True)
    manifest['fixture_red_green_validation']='PASS'if all(t['red_green']=='PASS'for t in manifest['tasks'])else'FAIL'
    manifest['prepared_task_count']=len(chosen);manifest['full_suite_prepared']=len(chosen)==30
    save(output/'manifest.json',manifest)
    return manifest


def main():
    parser=argparse.ArgumentParser(description=__doc__);commands=parser.add_subparsers(dest='command',required=True)
    p=commands.add_parser('prepare');p.add_argument('--output',type=Path,required=True);p.add_argument('--task-id',action='append')
    a=commands.add_parser('accept');a.add_argument('--task-id',required=True);a.add_argument('--repo',type=Path,required=True);a.add_argument('--candidate',required=True);a.add_argument('--output',type=Path)
    c=commands.add_parser('catalog');c.add_argument('--output',type=Path)
    args=parser.parse_args()
    try:
        if args.command=='prepare':result=prepare(args.output,args.task_id);return 0 if result['fixture_red_green_validation']=='PASS'else 1
        elif args.command=='accept':
            case=next(c for c in cases()if c['id']==args.task_id);result=evaluate(case,args.repo.resolve(),args.candidate)
        else:result={'cases':cases(),'configurations':configurations(),'live_executed':False}
        if args.output:save(args.output,result)
        print(json.dumps(result,ensure_ascii=False,indent=2));return 0 if result.get('status','PASS')=='PASS'else 1
    except Exception as exc:
        print(json.dumps({'status':'ERROR','error':str(exc)},ensure_ascii=False),file=sys.stderr);return 2

if __name__=='__main__':raise SystemExit(main())
